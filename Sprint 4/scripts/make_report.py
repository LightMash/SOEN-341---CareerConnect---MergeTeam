#!/usr/bin/env python3
"""Build a static-analysis report table from ruff, bandit and ESLint JSON output.

Usage (from the "Sprint 4" folder):
    python3 scripts/make_report.py \
        --input docs/static-analysis/baseline --suffix baseline \
        --output docs/static-analysis/report-01-baseline.md --title "Report 01 - Baseline"

Expects these files in --input (any missing file is skipped):
    ruff-<suffix>.json  bandit-<suffix>.json  eslint-<suffix>.json

Status and Fix commit columns are left for you to fill in by hand.
"""
import argparse
import json
import os
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # the "Sprint 4" folder


def rel(path: str, prefix: str = "") -> str:
    """Make a path relative to the Sprint 4 folder (tools often report absolute paths)."""
    p = Path(path)
    if p.is_absolute():
        for base, cand in ((ROOT, p), (ROOT, p.resolve())):
            try:
                return cand.relative_to(base).as_posix()
            except ValueError:
                pass
        # last resort: cut at the last "Sprint 4/" in the path
        marker = "Sprint 4/"
        text = p.as_posix()
        return text.split(marker, 1)[1] if marker in text else text
    return (Path(prefix) / os.path.normpath(path)).as_posix()


def ruff_type(code: str) -> tuple[str, str]:
    """Rule prefix -> (type, severity). Ruff has no severity of its own."""
    if re.match(r"S\d", code):  # flake8-bandit rules are S + digits (SIM rules are not security)
        return "Vulnerability", "Medium"
    if code.startswith(("F", "B")) or code in ("E902",) or code.startswith("E9"):
        return "Bug", "Medium"
    return "Smell", "Low"  # E501, SIM, C90, UP and other style/maintainability rules


def load(path: Path):
    if not path.exists():
        print(f"  (skipped, not found: {path})")
        return None
    text = path.read_text().strip()
    return json.loads(text) if text else None


def ruff_rows(data):
    for item in data or []:
        typ, sev = ruff_type(item["code"])
        yield ("ruff", item["code"], f'{rel(item["filename"], "backend")}:{item["location"]["row"]}',
               sev, typ, item["message"])


def bandit_rows(data):
    for item in (data or {}).get("results", []):
        yield ("bandit", item["test_id"], f'{rel(item["filename"], "backend")}:{item["line_number"]}',
               item["issue_severity"].title(), "Vulnerability", item["issue_text"])


def eslint_rows(data):
    for f in data or []:
        for m in f.get("messages", []):
            is_error = m.get("severity") == 2
            yield ("eslint", m.get("ruleId") or "parse-error", f'{rel(f["filePath"])}:{m.get("line", 0)}',
                   "Medium" if is_error else "Low", "Bug" if is_error else "Smell", m["message"])


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True, help="folder holding the raw JSON files")
    ap.add_argument("--suffix", required=True, help="e.g. baseline or after-fixes")
    ap.add_argument("--output", required=True, help="markdown file to write")
    ap.add_argument("--title", default="Static analysis report")
    ap.add_argument("--accepted", help="JSON file: {\"RULE\" or \"RULE@path-prefix\": \"reason\"} -> Status=Accepted")
    a = ap.parse_args()

    accepted = json.loads(Path(a.accepted).read_text()) if a.accepted else {}

    def accepted_reason(rule, loc):
        path = loc.rsplit(":", 1)[0]
        for key, why in accepted.items():
            r, _, prefix = key.partition("@")
            if r == rule and path.startswith(prefix):
                return why
        return None

    inp = Path(a.input)
    rows = []
    rows += ruff_rows(load(inp / f"ruff-{a.suffix}.json"))
    rows += bandit_rows(load(inp / f"bandit-{a.suffix}.json"))
    rows += eslint_rows(load(inp / f"eslint-{a.suffix}.json"))
    order = {"bandit": 0, "ruff": 1, "eslint": 2}
    sev_order = {"High": 0, "Medium": 1, "Low": 2}
    rows.sort(key=lambda r: (order[r[0]], sev_order.get(r[3], 3), r[1], r[2]))

    out = [f"# {a.title}", "",
           "Generated by `scripts/make_report.py` from the raw tool output in "
           f"`{rel(a.input) if Path(a.input).is_absolute() else a.input}`. Status is Open unless the finding is listed in the accepted file (then Accepted, with the reason in the last column). Update Status and Fix commit by hand as findings are fixed.", "",
           "## Summary", "", f"Total findings: **{len(rows)}**", "",
           "| Tool | Findings |", "|---|---|"]
    for tool, n in sorted(Counter(r[0] for r in rows).items(), key=lambda x: order[x[0]]):
        out.append(f"| {tool} | {n} |")
    out += ["", "| Type | Findings |", "|---|---|"]
    for typ, n in Counter(r[4] for r in rows).most_common():
        out.append(f"| {typ} | {n} |")
    out += ["", "Type/severity mapping: bandit = Vulnerability (bandit's own severity); ruff `S` = Vulnerability, "
            "`F`/`B` = Bug, everything else = Smell; ESLint error = Bug, warning = Smell.", "",
            "## Findings", "",
            "| # | Tool | Rule | File:line | Severity | Type | Message | Status | Fix commit |",
            "|---|------|------|-----------|----------|------|---------|--------|------------|"]
    for i, (tool, rule, loc, sev, typ, msg) in enumerate(rows, 1):
        why = accepted_reason(rule, loc)
        status, note = ("Accepted", cell(why)) if why else ("Open", "")
        out.append(f"| {i} | {tool} | {cell(rule)} | {cell(loc)} | {sev} | {typ} | {cell(msg)} | {status} | {note} |")
    Path(a.output).write_text("\n".join(out) + "\n")
    print(f"Wrote {a.output} with {len(rows)} findings")


if __name__ == "__main__":
    main()
